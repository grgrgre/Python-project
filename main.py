import sqlite3          # бібліотека для роботи з базою даних SQLite
from datetime import datetime  # клас для роботи з датою і часом

# ─────────────────────────────────────────────────────────────────────────────
# ПІДКЛЮЧЕННЯ ДО БАЗИ ДАНИХ
# ─────────────────────────────────────────────────────────────────────────────

# Відкриваємо файл finances.db як базу даних
# Якщо файлу не існує — SQLite автоматично його створить
conn = sqlite3.connect("finances.db")

# Виконуємо SQL-запит який створює таблицю transactions
# IF NOT EXISTS — не падає з помилкою якщо таблиця вже є
conn.execute("""
    CREATE TABLE IF NOT EXISTS transactions (
        id       INTEGER PRIMARY KEY AUTOINCREMENT,  -- номер рядка, зростає сам: 1, 2, 3...
        amount   REAL    NOT NULL,                   -- сума: число з комою, обов'язкове
        category TEXT    NOT NULL,                   -- категорія: текст, обов'язкове
        note     TEXT,                               -- примітка: текст, може бути порожнім
        date     TEXT    NOT NULL                    -- дата: текст формату "2025-01-31"
    )
""")

# Підтверджуємо зміни — без commit() таблиця не збережеться у файл
conn.commit()


# ─────────────────────────────────────────────────────────────────────────────
# ФУНКЦІЯ 1 — ДОДАТИ ТРАНЗАКЦІЮ
# ─────────────────────────────────────────────────────────────────────────────

def add_transaction():
    # try/except — якщо щось піде не так, програма не впаде
    try:
        # input() повертає рядок, float() перетворює його в число
        # наприклад: "200" → 200.0,  "-50" → -50.0
        # якщо ввести "abc" — float() кине ValueError, підхопить except
        amount = float(input("Сума (- витрата, + прибуток): "))

        # Не дозволяємо зберігати нульову суму
        # return print(...) — спочатку виводить текст, потім виходить з функції
        if amount == 0:
            return print("Сума не може бути 0")

        # input() зчитує текст від користувача
        # .strip() прибирає пробіли з країв: "  Їжа  " → "Їжа"
        # or "Інше" — якщо рядок порожній (""), підставляє "Інше"
        category = input("Категорія: ").strip() or "Інше"

        # Примітка не обов'язкова — просто зберігаємо що ввів користувач
        note = input("Примітка: ").strip()

        # datetime.now() — поточний момент часу
        # .strftime("%Y-%m-%d") — форматує в рядок: рік-місяць-день
        # наприклад: "2025-01-31"
        date = datetime.now().strftime("%Y-%m-%d")

        # INSERT INTO — додає новий рядок у таблицю
        # VALUES (NULL, ?, ?, ?, ?) — NULL для id (SQLite призначить сам)
        # ? — плейсхолдери, значення підставляються з кортежу нижче
        # це безпечніше ніж f-string — SQLite сам екранує спецсимволи
        conn.execute(
            "INSERT INTO transactions VALUES (NULL, ?, ?, ?, ?)",
            (amount, category, note, date)  # ці значення підставляться замість ?
        )

        # Підтверджуємо збереження — без commit() рядок не запишеться у файл
        conn.commit()

        print("✓ Збережено")

    # Якщо float() не зміг перетворити текст — перехоплюємо помилку
    # і виводимо зрозуміле повідомлення замість технічної помилки
    except ValueError:
        print("Помилка: введи число")


# ─────────────────────────────────────────────────────────────────────────────
# ФУНКЦІЯ 2 — ПОКАЗАТИ ЗВЕДЕННЯ
# ─────────────────────────────────────────────────────────────────────────────

def show_summary():
    # SELECT — читаємо дані з таблиці, беремо тільки потрібні стовпці
    # .fetchall() — повертає всі рядки як список кортежів
    # наприклад: [(200.0, "Їжа"), (-50.0, "Транспорт"), (5000.0, "Зарплата")]
    rows = conn.execute("SELECT amount, category FROM transactions").fetchall()

    # Якщо список порожній — таблиця пуста, виходимо з функції
    if not rows:
        return print("Записів ще немає")

    # Генераторний вираз — проходимо по рядках, беремо лише суму (a)
    # _ означає "ця змінна нам не потрібна" (ігноруємо category)
    # sum() складає всі суми → отримуємо загальний баланс
    total = sum(a for a, _ in rows)

    # Збираємо суму по кожній категорії у словник
    cats = {}  # порожній словник: { "Їжа": 0, "Транспорт": 0, ... }
    for amount, category in rows:
        # cats.get(category, 0) — якщо ключ є, повертає його значення
        # якщо ключа ще немає — повертає 0 (починаємо рахувати з нуля)
        cats[category] = cats.get(category, 0) + amount

    # :+.2f — форматування числа:
    # + завжди показує знак (+ або -)
    # .2f — два знаки після коми
    # наприклад: 200.0 → "+200.00",  -50.0 → "-50.00"
    print(f"\nБаланс: {total:+.2f} грн")

    # Виводимо суму по кожній категорії
    for category, amount in cats.items():
        print(f"  {category}: {amount:+.2f} грн")


# ─────────────────────────────────────────────────────────────────────────────
# ФУНКЦІЯ 3 — ПОКАЗАТИ ВСІ ТРАНЗАКЦІЇ
# ─────────────────────────────────────────────────────────────────────────────

def show_transactions():
    # ORDER BY id DESC — сортуємо за id від більшого до меншого
    # тобто найновіші записи будуть першими у списку
    rows = conn.execute(
        "SELECT amount, category, note, date FROM transactions ORDER BY id DESC"
    ).fetchall()

    # Якщо немає жодного запису — повідомляємо і виходимо
    if not rows:
        return print("Немає транзакцій")

    # Виводимо заголовок таблиці з вирівнюванням
    # :>10 — вирівнювання по правому краю, ширина 10 символів
    # :<15 — вирівнювання по лівому краю, ширина 15 символів
    # завдяки цьому всі рядки вирівняні — виходить охайна таблиця
    print(f"\n{'Сума':>10}  {'Категорія':<15}  {'Примітка':<20}  Дата")
    print("-" * 65)  # горизонтальна лінія з 65 символів "-"

    # Розпаковуємо кожен кортеж у окремі змінні і виводимо рядок
    for amount, category, note, date in rows:
        print(f"{amount:>+10.2f}  {category:<15}  {note:<20}  {date}")


# ─────────────────────────────────────────────────────────────────────────────
# СЛОВНИК МЕНЮ
# ─────────────────────────────────────────────────────────────────────────────

# Ключ — цифра яку вводить користувач
# Значення — функція яку треба викликати (без дужок! просто посилання)
# MENU["1"] — це сама функція
# MENU["1"]() — це виклик функції
MENU = {
    "1": add_transaction,   # цифра 1 → викличе add_transaction()
    "2": show_summary,      # цифра 2 → викличе show_summary()
    "3": show_transactions, # цифра 3 → викличе show_transactions()
}


# ─────────────────────────────────────────────────────────────────────────────
# ГОЛОВНИЙ ЦИКЛ ПРОГРАМИ
# ─────────────────────────────────────────────────────────────────────────────

# while True — нескінченний цикл, крутиться поки не зустріне break
while True:
    # Виводимо меню кожного разу на початку циклу
    print("\n=== Трекер фінансів ===")
    print("1. Додати транзакцію")
    print("2. Зведення")
    print("3. Всі транзакції")
    print("0. Вийти")

    # .strip() — прибирає пробіли якщо користувач випадково натиснув пробіл
    choice = input("Вибір: ").strip()

    if choice == "0":
        conn.close()        # коректно закриваємо базу перед виходом
        print("До побачення!")
        break               # виходимо з while True — програма завершується

    elif choice in MENU:    # перевіряємо чи є такий ключ у словнику
        MENU[choice]()      # знаходимо функцію у словнику і викликаємо її

    else:
        print("Невідомий пункт")  # якщо ввели щось крім 0, 1, 2, 3
